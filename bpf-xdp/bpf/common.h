/*
 * Структуры, общие для BPF-программы (в ядре) и загрузчика (в userspace).
 * Через них фильтр и обычная программа договариваются, как выглядят данные
 * в BPF map.
 */
#pragma once

#include <linux/types.h>

/* Сколько пакетов в секунду разрешено с одного IP-адреса. */
#define RPS_LIMIT 5

/* Длина «окна подсчёта»: одна секунда в наносекундах. */
#define RPS_WINDOW_NS 1000000000ULL

/* map `rates`: ключ - IPv4-адрес отправителя, значение - состояние окна. */
struct rate_entry {
  __u64 window_start_ns; /* когда началось текущее окно */
  __u32 count; /* сколько пакетов уже пришло в этом окне */
  __u32 pad; /* выравнивание до 16 байт */
};

/* map `stats`: ключ - IPv4-адрес отправителя, значение - счётчики. */
struct stat_entry {
  __u64 passed;  /* сколько пакетов пропущено */
  __u64 dropped; /* сколько пакетов отброшено */
};
